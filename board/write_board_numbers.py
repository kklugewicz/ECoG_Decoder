"""Collect the board study into numbers_board.tex (run on the host).

Sources (in the paper: Radxa ZERO 3, RK3566 4x Cortex-A55 @ 1.8 GHz,
performance governor, heatsink + fan, suspend masked), all in one folder:
  accuracy.json, board_int8_scores.csv   per-call latency, 15 emit-10 models
  soak.json                              10-minute sustained run
  paced_sleep_*                          full test recordings replayed at 100 Hz

    python board/write_board_numbers.py --results results/board   # the paper's run
"""
import argparse
import csv
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(HERE, "results"))
    ap.add_argument("--out", default=os.path.join(REPO, "figures", "tex"))
    ap.add_argument("--board-name",
                    default="Radxa ZERO~3 (RK3566, 4$\\times$Cortex-A55 @ 1.8\\,GHz)")
    a = ap.parse_args()
    R = a.results

    acc = json.load(open(os.path.join(R, "accuracy.json")))
    soak = json.load(open(os.path.join(R, "soak.json")))
    scores = os.path.join(R, "board_int8_scores.csv")

    med = np.median([v["latency"]["median"] for v in acc.values()])
    p95 = np.median([v["latency"]["p95"] for v in acc.values()])

    ages = np.concatenate([np.load(p) for p in sorted(glob.glob(
        os.path.join(R, "paced_sleep_sub*_age_ms.npy")))])
    miss = int((ages > 100.0).sum())
    temps = [json.load(open(p))["thermal"]["temp_max"] for p in glob.glob(
        os.path.join(R, "paced_sleep_sub*.json"))]

    b = [float(r["board_official_r"]) for r in csv.DictReader(open(scores))]
    d = [abs(float(r["diff"])) for r in csv.DictReader(open(scores))]

    os.makedirs(a.out, exist_ok=True)
    out = os.path.join(a.out, "numbers_board.tex")
    with open(out, "w") as f:
        f.write("% AUTO-GENERATED by board/write_board_numbers.py. Do not edit.\n")

        def cmd(n, v):
            f.write(f"\\newcommand{{\\{n}}}{{{v}}}\n")
        cmd("BoardName", a.board_name)
        cmd("BoardINTmean", f"{np.mean(b):.3f}")
        cmd("BoardHostMaxDiff", f"{max(d):.0e}".replace("e-0", "\\times10^{-") + "}")
        cmd("BoardCallMedianMs", f"{med:.1f}")
        cmd("BoardCallPninetyfiveMs", f"{p95:.1f}")
        cmd("BoardAgeMedianMs", f"{np.percentile(ages, 50):.1f}")
        cmd("BoardAgePninetynineMs", f"{np.percentile(ages, 99):.1f}")
        cmd("BoardAgePninetyninenineMs", f"{np.percentile(ages, 99.9):.1f}")
        cmd("BoardAgeMaxMs", f"{ages.max():.0f}")
        cmd("BoardMisses", f"{miss}")
        cmd("BoardBatches", f"{len(ages):,}")          # misses are counted per batch
        cmd("BoardLabels", f"{10 * len(ages):,}")      # E=10 labels per batch
        cmd("BoardMissPct", f"{100 * miss / len(ages):.2f}")
        cmd("BoardPacedTempMax", f"{max(temps):.0f}")
        cmd("BoardSoakSeconds", f"{soak['seconds']}")
        cmd("BoardSoakTempMax", f"{soak['thermal']['temp_max']:.0f}")
        cmd("BoardSoakMHzMin", f"{soak['thermal']['mhz_min']:.0f}")
    print(open(out).read())


if __name__ == "__main__":
    main()
